export const rankIcon = (rank?: Rank | null): LucideIcon => {
  const name = (rank?.Name || '').toLowerCase();
  if (name.includes('god') || name.includes('owner') || name.includes('founder')) return Crown;
  if (name.includes('dev')) return Code;
  if (name.includes('super') || name.includes('head') || name.includes('senior')) return ShieldPlus;
  if (name.includes('admin')) return ShieldCheck;
  if (name.includes('mod')) return Gavel;
  if (name.includes('support') || name.includes('helper')) return Headset;
  if (name.includes('trial') || name.includes('junior')) return ShieldHalf;
  return Shield;
};
